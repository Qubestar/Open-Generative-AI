"use client";

import { useEffect, useRef, useState } from 'react';
import previews from '../captionPreviews.json';
import { CAPTION_COLORS, CAPTION_FONTS, CAPTION_LOOKS, normalizeCaptionColor } from '../captionStudioModel.mjs';

export default function CaptionStudio({ settings, onChange, disabled, previewUrl }) {
  const dialog = useRef(null);
  const [open, setOpen] = useState(false);
  const [frame, setFrame] = useState(0);
  const [playing, setPlaying] = useState(true);
  const look = CAPTION_LOOKS.find(item => item.id === settings.captionStyle) || CAPTION_LOOKS[0];
  const background = settings.captionBackground !== false ? 'box' : 'clear';
  const assets = previews[look.id].backgrounds[background];
  const captionColor = normalizeCaptionColor(settings.captionColor);
  const captionFont = CAPTION_FONTS.find(font => font.id === settings.captionFont) || CAPTION_FONTS[0];
  const previewFont = captionFont.id === 'preset'
    ? (['bold', 'outline', 'pop'].includes(look.id) ? 'Vidmyo Anton' : 'Vidmyo Barlow Condensed')
    : captionFont.family;
  const change = update => onChange(current => ({ ...current, ...update }));
  useEffect(() => {
    setFrame(0);
    if (!open || !playing) return;
    const timer = setInterval(() => setFrame(value => value + 1), 450);
    return () => clearInterval(timer);
  }, [open, playing, look.id]);
  const offset = ({ upper: 1160, middle: 1380, lower: 1580 }[settings.captionPosition] - 1380) / 1920 * 100;
  return <div className="rep-caption-control">
    <button className="rep-caption-launch" disabled={disabled} onClick={() => { setOpen(true); dialog.current.showModal(); }}>
      <img src={assets.thumbnail} alt="" /><span><b>{look.name}</b><small>Choose a caption look →</small></span>
    </button>
    <p className="rep-delivery__hint">{settings.captionBackground !== false ? 'Background on' : 'No background'} · {settings.captionPosition} position · {captionFont.name}. Changes apply when you Finish.</p>
    <dialog ref={dialog} className="rep-caption-dialog" aria-labelledby="caption-studio-title" onClose={() => setOpen(false)}>
      <header><div><p className="rep-kicker">Caption studio</p><h2 id="caption-studio-title">Find your voice. Visually.</h2></div><button autoFocus aria-label="Close caption studio" onClick={() => dialog.current.close()}>×</button></header>
      <div className="rep-caption-layout">
        <div className="rep-caption-demo">
          <div className="rep-caption-portrait">
            {open && previewUrl ? <video src={previewUrl} muted controls playsInline aria-label="Caption style background video" /> : <div className="rep-caption-placeholder"><span>YOUR<br />NEXT<br />GREAT<br />MOMENT.</span></div>}
            <img className="rep-caption-overlay" src={assets.frames[frame % assets.frames.length]} alt={`${look.name} sample: Make every word count.`} style={{ transform: `translateY(${offset}%)` }} />
            <span className="rep-caption-demo-label">9:16 · STYLE DEMO</span>
          </div>
          <button className="rep-button rep-button--quiet" onClick={() => setPlaying(value => !value)}>{playing ? 'Pause caption demo' : 'Play caption demo'}</button>
          <p>Sample words, not your transcript. Final captions use your clip’s actual words and timings. Preview typography is generated by the export renderer.</p>
        </div>
        <div className="rep-caption-options">
          <div className="rep-caption-grid" role="group" aria-label="Caption looks">{CAPTION_LOOKS.map(item => <button key={item.id} aria-pressed={look.id === item.id} onClick={() => change({ captionStyle: item.id })}>
            <span className="rep-caption-tag">{item.tag}</span><img src={previews[item.id].backgrounds[background].thumbnail} alt="" /><b>{item.name}</b><small>{item.description}</small>
          </button>)}</div>
          <div className="rep-caption-adjustments">
            <div className="rep-caption-brand-sample" style={{ color: captionColor === 'preset' ? undefined : captionColor, fontFamily: previewFont }}><span className={settings.captionBackground === false ? 'is-clear' : ''}>Make every word count.</span></div>
            <fieldset className="rep-caption-colors"><legend>Caption color</legend>{CAPTION_COLORS.map(color => <button key={color.id} type="button" aria-pressed={captionColor === color.id} onClick={() => change({ captionColor: color.id })}><i style={{ background: color.color || 'conic-gradient(#fff, #ffe34d, #9bffbb, #fff)' }} />{color.name}</button>)}<label><input aria-label="Custom caption color" type="color" value={captionColor === 'preset' ? '#7C5CFF' : captionColor} onChange={event => change({ captionColor: event.target.value.toUpperCase() })} /><span>Custom</span></label></fieldset>
            <label className="rep-delivery__select"><span>Caption font</span><select value={captionFont.id} onChange={event => change({ captionFont: event.target.value })}>{CAPTION_FONTS.map(font => <option key={font.id} value={font.id}>{font.name}</option>)}</select></label>
            <label className="rep-delivery__toggle"><input type="checkbox" checked={settings.captionBackground !== false} onChange={event => change({ captionBackground: event.target.checked })} /><span>Text background</span></label>
            <p>Switch off for floating text. Outlines stay on for contrast.</p>
            <label className="rep-delivery__select"><span>Caption position</span><select value={settings.captionPosition} onChange={event => change({ captionPosition: event.target.value })}><option value="upper">Higher</option><option value="middle">Middle</option><option value="lower">Lower</option></select></label>
          </div>
          <footer><span>{look.name} · {captionFont.name} · {background === 'box' ? 'with background' : 'no background'}</span><button className="rep-button rep-button--primary" onClick={() => dialog.current.close()}>Use this look</button></footer>
        </div>
      </div>
    </dialog>
  </div>;
}
